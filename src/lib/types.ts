/** Display name for a Pokémon slug: "mr-mime" -> "Mr. Mime", "tapu-koko" -> "Tapu Koko". */
export const pokemonLabel = (slug: string): string =>
  SPECIAL_NAMES[slug] ??
  slug
    .split('-')
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(' ')
